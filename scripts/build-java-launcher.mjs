#!/usr/bin/env node
/**
 * Compiles the playground's Java support classes — JpStdioLauncher, JpJdkStage
 * and JpServer — and writes public/java-playground/jp-launcher-<hash>.jar plus
 * src/lib/java-playground/launcherAsset.ts.
 *
 * Targets Java 8 bytecode deliberately: it is the safe floor, and it loads on
 * CheerpJ's Java 17 runtime just as well as anything newer would.
 *
 * The GitHub Pages build has no JDK, so the jar is committed. This script
 * no-ops when the hashed jar already exists, or when javac is missing and a
 * jar is present.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const sourceDir = path.join(root, 'scripts/java');
/** Every class the playground runs inside CheerpJ, packed into one jar. */
const sourceNames = ['JpStdioLauncher.java', 'JpJdkStage.java', 'JpServer.java'];
const sourcePaths = sourceNames.map((name) => path.join(sourceDir, name));
const destDir = path.join(root, 'public/java-playground');
const assetPath = path.join(root, 'src/lib/java-playground/launcherAsset.ts');
const force = process.argv.includes('--force');

for (const file of sourcePaths) {
  if (!fs.existsSync(file)) throw new Error(`Missing launcher source: ${file}`);
}

/** JpServer compiles with ECJ's BatchCompiler, so ECJ has to be on the classpath. */
function ecjJar() {
  const jars = fs
    .readdirSync(destDir)
    .filter((name) => /^ecj-[\d.]+\.jar$/.test(name))
    .sort();
  if (jars.length === 0) {
    throw new Error(
      'No ECJ jar in public/java-playground. Run scripts/fetch-java-playground-assets.mjs first.',
    );
  }
  return path.join(destDir, jars[jars.length - 1]);
}

// Hash the newline-normalized source so the jar name is the same on Windows
// checkouts (CRLF) and CI (LF); otherwise the committed jar never matches.
const normalized = sourcePaths
  .map((file) => fs.readFileSync(file).toString('utf8').replace(/\r\n/g, '\n'))
  .join('\u0000');
const hash = createHash('sha256').update(normalized, 'utf8').digest('hex').slice(0, 8);
const filename = `jp-launcher-${hash}.jar`;
const dest = path.join(destDir, filename);

function writeAsset() {
  const contents = `/** Generated by scripts/build-java-launcher.mjs. Do not edit. */\nexport const LAUNCHER_FILENAME = '${filename}';\n`;
  fs.mkdirSync(path.dirname(assetPath), { recursive: true });
  fs.writeFileSync(assetPath, contents);
}

function findBinary(name) {
  const envKey = name.toUpperCase();
  if (process.env[envKey]) return process.env[envKey];
  const home = process.env.JAVA_HOME;
  const candidates = [
    home ? path.join(home, 'bin', name) : null,
    `/opt/homebrew/opt/openjdk/bin/${name}`,
    `/usr/lib/jvm/default-java/bin/${name}`,
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) return candidate;
  }
  return name;
}

function existingLauncherJars() {
  if (!fs.existsSync(destDir)) return [];
  return fs.readdirSync(destDir).filter((name) => /^jp-launcher-[0-9a-f]+\.jar$/.test(name));
}

if (!force && fs.existsSync(dest) && fs.statSync(dest).size > 200) {
  writeAsset();
  console.log(`java-playground: using existing ${path.relative(root, dest)}`);
  process.exit(0);
}

if (!force && !fs.existsSync(dest)) {
  const previous = existingLauncherJars();
  if (previous.length > 0) {
    // Keep going — source changed, rebuild if javac is available.
  }
}

const javac = findBinary('javac');
let javacOk = false;
try {
  execFileSync(javac, ['-version'], { stdio: 'pipe' });
  javacOk = true;
} catch {
  javacOk = false;
}

if (!javacOk) {
  const previous = existingLauncherJars()[0];
  if (previous) {
    console.warn(
      `java-playground: javac not found; leaving ${previous}. Run this script locally to rebuild.`,
    );
    process.exit(0);
  }
  throw new Error('javac not found and no jp-launcher-*.jar is present. Install a JDK or commit the jar.');
}

fs.mkdirSync(destDir, { recursive: true });
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'jp-launcher-'));
try {
  execFileSync(javac, ['--release', '8', '-nowarn', '-cp', ecjJar(), '-d', tmp, ...sourcePaths], {
    stdio: 'pipe',
  });
  const produced = fs.readdirSync(tmp).filter((name) => name.endsWith('.class'));
  for (const name of sourceNames) {
    const expected = name.replace('.java', '.class');
    if (!produced.includes(expected)) throw new Error(`javac did not produce ${expected}`);
  }

  const jar = findBinary('jar');
  const classArgs = produced.flatMap((name) => ['-C', tmp, name]);
  let packed = false;
  try {
    execFileSync(jar, ['cf', dest, ...classArgs], { stdio: 'pipe' });
    packed = true;
  } catch {
    packed = false;
  }
  if (!packed) {
    execFileSync('zip', ['-q', dest, ...produced], { cwd: tmp, stdio: 'pipe' });
  }
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}

if (!fs.existsSync(dest) || fs.statSync(dest).size < 200) {
  throw new Error(`Failed to write ${dest}`);
}

for (const name of existingLauncherJars()) {
  if (name !== filename) {
    fs.unlinkSync(path.join(destDir, name));
  }
}

writeAsset();
console.log(`java-playground: wrote ${path.relative(root, dest)} (${fs.statSync(dest).size} bytes)`);
